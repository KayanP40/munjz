export function serviceItemDescription(service: ServiceItem): string {
  const parts: string[] = [];
  if (service.body) parts.push(service.body);
  if (service.subtypes?.length) {
    parts.push(`الأنواع: ${service.subtypes.join("، ")}`);
  }
  if (service.items?.length) {
    parts.push(service.items.join(" "));
  }
  return parts.join(" ").trim();
}
